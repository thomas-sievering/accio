import { expect, test } from '@playwright/test';
import { pick } from './menu-select';

test('automatic naming, inline and sidebar rename, regeneration and settings preview persist', async ({ page, baseURL }, testInfo) => {
  await page.goto(`${baseURL}/#token=isolated-chat-test-token`);
  await page.locator('.sidebar').getByRole('button', { name: 'New thread', exact: true }).click();
  await page.getByRole('option', { name: 'No project', exact: true }).click();
  if (await page.getByRole('combobox', { name: 'Search profiles' }).isVisible()) await page.getByRole('option', { name: 'Personal', exact: true }).click();
  await page.locator('.composer textarea').fill('Naming fixture: fix the login redirect after sign-in');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  const title = page.getByRole('button', { name: 'Rename thread: Fix login redirects', exact: true });
  await expect(title).toBeVisible();
  await expect(page.locator('.messages')).toContainText('The login redirect loops');
  await title.click();
  await page.getByRole('textbox', { name: 'Thread title', exact: true }).fill('My login investigation');
  await page.locator('.thread-title-form').getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Rename thread: My login investigation', exact: true })).toBeVisible();
  await page.reload();
  await page.locator('.row-main').filter({ hasText: 'My login investigation' }).click();
  await expect(page.getByRole('button', { name: 'Rename thread: My login investigation', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Thread actions', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Regenerate title', exact: true }).click();
  await expect(title).toBeVisible();
  await page.keyboard.press('Escape');

  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  const naming = page.locator('.sidebar nav').getByRole('button', { name: 'Thread naming', exact: true });
  await naming.click();
  await expect(page.getByRole('checkbox', { name: 'Automatically name new threads' })).toBeChecked();
  await page.getByText('Advanced', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Naming instructions' }).fill('Use German');
  await pick(page, 'Example thread', 'Fix login redirects');
  await page.getByRole('button', { name: 'Try instructions', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Anmeldung reparieren');
  await page.screenshot({ path: testInfo.outputPath('naming-settings.png') });
  // Preview is unsaved and cannot rename the thread.
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(title).toBeVisible();
  await page.getByRole('button', { name: 'Settings', exact: true }).click(); await naming.click();
  await page.getByText('Advanced', { exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Naming instructions' })).toHaveValue('');
  await page.getByRole('textbox', { name: 'Naming instructions' }).fill('Use German');
  await pick(page, 'Naming model', /^Claude Haiku\s*Claude Code/);
  await page.getByRole('checkbox', { name: 'Automatically name new threads' }).uncheck();
  await page.getByRole('button', { name: 'Save naming settings', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Naming settings saved');
  await page.reload();
  await page.getByRole('button', { name: 'Settings', exact: true }).click(); await naming.click();
  await expect(page.getByRole('checkbox', { name: 'Automatically name new threads' })).not.toBeChecked();
  await expect(page.getByRole('button', { name: 'Naming model', exact: true })).toHaveText('Claude Haiku');
  await page.getByText('Advanced', { exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Naming instructions' })).toHaveValue('Use German');
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  const row = page.locator('.row-main').filter({ hasText: 'Fix login redirects' });
  await row.click({ button: 'right' });
  await page.getByRole('menuitem', { name: /^Rename/ }).click();
  await page.getByRole('textbox', { name: 'Thread title' }).fill('Sidebar login title');
  await page.getByRole('textbox', { name: 'Thread title' }).press('Enter');
  await expect(page.getByRole('button', { name: 'Rename thread: Sidebar login title', exact: true })).toBeVisible();
  await page.locator('.row-main').filter({ hasText: 'Sidebar login title' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Regenerate title', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Rename thread: Anmeldung reparieren', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('named-thread.png') });
  // Restore shared fixture preferences for the other browser journeys.
  await page.getByRole('button', { name: 'Settings', exact: true }).click(); await naming.click();
  await page.getByRole('checkbox', { name: 'Automatically name new threads' }).check();
  await pick(page, 'Naming model', /^Automatic/);
  await page.getByText('Advanced', { exact: true }).click();
  await page.getByRole('button', { name: 'Reset instructions', exact: true }).click();
  await page.getByRole('button', { name: 'Save naming settings', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Naming settings saved');
});
